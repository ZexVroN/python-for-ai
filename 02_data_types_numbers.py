# Addition and subtraction
total = 10 + 5  # 15
change = 20 - 7  # 13

# Multiplication and division
area = 6 * 4  # 24
half = 10 / 2  # 5.0 (always returns float)

# Powers
squared = 5**2  # 25
cubed = 2**3  # 8

# Regular division (always float)
result = 10 / 3  # 3.333...

# Integer division (rounds down)
result = 10 // 3  # 3
